#!/usr/bin/env python3
"""
Generate the 1-bit fonts for the 64x32 OLED: the weight digits (src/ui/font_digits.h)
and, with --name small, the smaller letters the Voltra picker shows (src/ui/font_small.h).

Each glyph is rendered from a TTF at 8x oversampling, cropped to its ink, squeezed
horizontally to at most --max-width pixels (three digits plus two gaps have to fit in
64 columns) and scaled to --height pixels tall, then thresholded. The C header stores
each glyph as one uint32_t per row, bit 0 = leftmost pixel.

    python tools/gen_digits.py --ttf tools/Poppins-Bold.ttf --out src/ui/font_digits.h \
        --preview digits.png
    python tools/gen_digits.py --ttf tools/Poppins-Bold.ttf --out src/ui/font_small.h \
        --name small --height 16 --max-width 9 --chars "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ-:"
"""
import argparse

from PIL import Image, ImageDraw, ImageFont

OVERSAMPLE = 8


def render(font, ch, height, max_width, threshold):
    big = height * OVERSAMPLE
    img = Image.new("L", (big * 3, big * 3), 0)
    ImageDraw.Draw(img).text((big, big), ch, font=font, fill=255)
    box = img.getbbox()
    ink = img.crop(box)
    # all glyphs share the digits' height: the em size was picked so "0" is `height` tall
    scale = height / ref_height
    w = max(1, round(ink.width / OVERSAMPLE * scale))
    h = max(1, round(ink.height / OVERSAMPLE * scale))
    w = min(w, max_width)
    small = ink.resize((w, h), Image.LANCZOS)
    rows = []
    # vertical placement: keep the glyph's own top offset relative to the digits' top
    top = round((box[1] - ref_top) / OVERSAMPLE * scale)
    for y in range(height):
        bits = 0
        sy = y - top
        if 0 <= sy < h:
            for x in range(w):
                if small.getpixel((x, sy)) >= threshold:
                    bits |= 1 << x
        rows.append(bits)
    return w, rows


def main():
    global ref_height, ref_top
    ap = argparse.ArgumentParser()
    ap.add_argument("--ttf", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--height", type=int, default=32, help="digit height in pixels")
    ap.add_argument("--max-width", type=int, default=20, help="widest a glyph may be")
    ap.add_argument("--threshold", type=int, default=110, help="0-255 ink cut-off")
    ap.add_argument("--chars", default="0123456789-OF")
    ap.add_argument("--preview", help="write a PNG of the glyphs, 4x enlarged")
    ap.add_argument("--name", default="digit", help="C names: <NAME>_FONT, <Name>Glyph")
    a = ap.parse_args()

    big = a.height * OVERSAMPLE
    font = ImageFont.truetype(a.ttf, big)
    probe = Image.new("L", (big * 3, big * 3), 0)
    ImageDraw.Draw(probe).text((big, big), "0", font=font, fill=255)
    pb = probe.getbbox()
    ref_top, ref_height = pb[1], (pb[3] - pb[1]) / OVERSAMPLE

    glyphs = []
    for ch in a.chars:
        if ch == "-":
            # Poppins' hyphen is short and thin; a bolder bar reads better on its own
            w = round(a.height * 12 / 32)
            t = round(a.height * 5 / 32)
            y0 = a.height // 2 - (t + 1) // 2
            rows = [((1 << w) - 1) if y0 <= y < y0 + t else 0 for y in range(a.height)]
        else:
            w, rows = render(font, ch, a.height, a.max_width, a.threshold)
        glyphs.append((ch, w, rows))

    up, cls = a.name.upper(), a.name.capitalize() + "Glyph"
    with open(a.out, "w", newline="\n") as f:
        f.write("#pragma once\n")
        f.write("// Generated by tools/gen_digits.py from %s -- do not edit.\n" % a.ttf.replace("\\", "/").split("/")[-1])
        f.write("// %d px tall, squeezed to at most %d px wide; one uint32_t per row, bit 0 = left.\n"
                % (a.height, a.max_width))
        f.write("#include <stdint.h>\n\n")
        f.write("constexpr int %s_FONT_H = %d;\n\n" % (up, a.height))
        f.write("struct %s {\n    char ch;\n    uint8_t w;\n    uint32_t rows[%d];\n};\n\n" % (cls, a.height))
        f.write("static const %s %s_FONT[] = {\n" % (cls, up))
        for ch, w, rows in glyphs:
            f.write("    {'%s', %d, {\n" % (ch, w))
            for i in range(0, len(rows), 4):
                f.write("        " + ", ".join("0x%08x" % r for r in rows[i:i + 4]) + ",\n")
            f.write("    }},\n")
        f.write("};\n")

    if a.preview:
        total = sum(w for _, w, _ in glyphs) + 2 * (len(glyphs) + 1)
        img = Image.new("L", (total, a.height + 4), 0)
        x = 2
        for _, w, rows in glyphs:
            for y, r in enumerate(rows):
                for i in range(w):
                    if r >> i & 1:
                        img.putpixel((x + i, y + 2), 255)
            x += w + 2
        img.resize((img.width * 4, img.height * 4), Image.NEAREST).save(a.preview)


if __name__ == "__main__":
    main()
